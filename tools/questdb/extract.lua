-- Builds RUIN_QuestData from a QuestieDB Forever build, for one faction.
-- usage: texlua+compat extract.lua <QuestieDB dir> <LibDeflate.lua> <wowenv.lua> <Alliance|Horde> <out.lua>
local FACTION = arg[4]
UnitFactionGroup = function() return FACTION end
UnitClassBase = function() return nil end      -- no class-only corrections: the data is for every class
UnitRace = function() return nil end
dofile(arg[3])
local L = LibQuestieDB_NS
local Q, N, O, I = L.Quest, L.Npc, L.Object, L.Item

local function fields(meta) local out = {} for i, n in ipairs(meta.names) do out[i] = n end return out end
local QF = fields(L.Meta.Quest)
local NF = { "name", "minLevel", "maxLevel", "spawns", "zoneID", "questStarts", "questEnds", "friendlyToFaction", "subName" }
local OF = { "name", "spawns", "zoneID", "questStarts", "questEnds" }
local IF = { "name", "npcDrops", "objectDrops", "itemDrops", "startQuest", "vendors" }

-- serialize compactly: numbers trimmed, spawn coordinates to 0.1
local function num(v)
    if math.type and math.type(v) == "integer" then return tostring(v) end
    if v == math.floor(v) then return string.format("%d", v) end
    return (string.format("%.2f", v):gsub("0+$", ""):gsub("%.$", ""))
end
local function ser(v, coords)
    local t = type(v)
    if t == "number" then
        if coords then v = math.floor(v * 10 + 0.5) / 10 end
        return num(v)
    elseif t == "string" then return string.format("%q", v):gsub("\\\n", "\\n")
    elseif t == "boolean" then return tostring(v)
    elseif t == "table" then
        local parts, n = {}, #v
        for i = 1, n do parts[#parts + 1] = v[i] == nil and "nil" or ser(v[i], coords) end
        local keys = {}
        for k in pairs(v) do if not (type(k) == "number" and k >= 1 and k <= n and math.floor(k) == k) then keys[#keys + 1] = k end end
        table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
        for _, k in ipairs(keys) do
            local ks = type(k) == "number" and ("[" .. num(k) .. "]") or (type(k) == "string" and k:match("^[%a_][%w_]*$") and k or ("[" .. string.format("%q", k) .. "]"))
            parts[#parts + 1] = ks .. "=" .. ser(v[k], coords)
        end
        return "{" .. table.concat(parts, ",") .. "}"
    end
    return "nil"
end

local function row(E, id, names, coordField)
    local out = {}
    local last = 0
    for i, f in ipairs(names) do
        local ok, val = pcall(E.Get, id, f)
        if ok and val ~= nil then out[i] = val; last = i end
    end
    if last == 0 then return nil end
    local parts = {}
    for i = 1, last do parts[i] = out[i] == nil and "nil" or ser(out[i], names[i] == coordField) end
    return "{" .. table.concat(parts, ",") .. "}"
end

-- what quests need: their givers, enders, targets and items (and where items drop)
local needN, needO, needI = {}, {}, {}
local qids = {}
for id in pairs(Q.GetAllIds(true)) do qids[#qids + 1] = id end
table.sort(qids)
local function addGivers(g)
    if type(g) ~= "table" then return end
    for _, id in ipairs(g[1] or {}) do needN[id] = true end
    for _, id in ipairs(g[2] or {}) do needO[id] = true end
    for _, id in ipairs(g[3] or {}) do needI[id] = true end
end
for _, id in ipairs(qids) do
    addGivers(Q.Get(id, "startedBy")); addGivers(Q.Get(id, "finishedBy"))
    local o = Q.Get(id, "objectives")
    if type(o) == "table" then
        for _, x in ipairs(o[1] or {}) do if type(x) == "table" then needN[x[1]] = true end end
        for _, x in ipairs(o[2] or {}) do if type(x) == "table" then needO[x[1]] = true end end
        for _, x in ipairs(o[3] or {}) do if type(x) == "table" then needI[x[1]] = true end end
        for _, x in ipairs(o[5] or {}) do if type(x) == "table" and type(x[1]) == "table" then for _, n in ipairs(x[1]) do needN[n] = true end end end
    end
    local src = Q.Get(id, "requiredSourceItems")
    for _, it in ipairs(type(src) == "table" and src or {}) do needI[it] = true end
end
for it in pairs(needI) do
    if I.Exists(it) then
        for _, n in ipairs(I.Get(it, "npcDrops") or {}) do needN[n] = true end
        for _, o in ipairs(I.Get(it, "objectDrops") or {}) do needO[o] = true end
    end
end

local out = {}
local function emit(s) out[#out + 1] = s end
local function section(name, ids, E, names, coordField)
    local list = {}
    for id in pairs(ids) do if E.Exists(id) then list[#list + 1] = id end end
    table.sort(list)
    local n = 0
    for k = 1, #list, 400 do
        emit("F(function(" .. name .. ")")
        for j = k, math.min(k + 399, #list) do
            local r = row(E, list[j], names, coordField)
            if r then emit(name .. "[" .. list[j] .. "]=" .. r); n = n + 1 end
        end
        emit("end)")
    end
    return n
end
emit("-- generated by tools/questdb/extract.lua for " .. FACTION .. "; see LICENSE and NOTICE")
local qset = {}
for _, id in ipairs(qids) do qset[id] = true end
local cq = section("q", qset, Q, QF)
local cn = section("n", needN, N, NF, "spawns")
local co = section("o", needO, O, OF, "spawns")
local ci = section("i", needI, I, IF)
-- zone maps
local support = L.Support and L.Support.Get and L.Support.Get("ZoneDB")
local private = type(support) == "table" and support.private or {}
local function readMap(text) if type(text) == "table" then return text end if type(text) ~= "string" then return nil end local c = load(text); local ok, t = pcall(c); return ok and t or nil end
local function merged(a, b)
    local m = {}
    for k, v in pairs(readMap(private[a]) or {}) do m[k] = v end
    for k, v in pairs(readMap(private[b]) or {}) do m[k] = v end
    return m
end
emit("F(function(_, z) z.areaToMap = " .. ser(merged("areaIdToUiMapId", "areaIdToUiMapIdOverride")) .. "; z.mapToArea = " .. ser(merged("uiMapIdToAreaId", "uiMapIdToAreaIdOverride")) .. " end)")
local f = assert(io.open(arg[5], "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
io.stderr:write(("%s: %d quests, %d NPCs, %d objects, %d items\n"):format(FACTION, cq, cn, co, ci))
-- the field names, for the reader
local ff = assert(io.open(arg[5] .. ".fields", "w"))
ff:write("Q=" .. ser(QF) .. "\nN=" .. ser(NF) .. "\nO=" .. ser(OF) .. "\nI=" .. ser(IF) .. "\n")
ff:close()
